
def main():
    # Create a list of words for our cheer
    CHEER = ["way", "to", "go", "team"]

    # Loop through each word in the CHEER list
    for word in CHEER:

        # Convert each individual word to uppercase
        # Add an exclamation mark after the word
        print(word.upper() + "!")


# Run the main function
if __name__ == "__main__":
    main()
